#WAP to calculate the area of rectangle\

#Take input 
l = int(input('Enter the length of rectangle:'))
b = int(input('Enter the breadth of rectangle:'))
bt = int(input('Enter the base of traingle:'))
ht= int(input('Enter the height of traingle:'))

# Perform operation 
a = l * b
at = 0.5 * bt * ht

#Display the result
print(f'The area of the rectangle is {a} & The area of Traingle is {at}')



